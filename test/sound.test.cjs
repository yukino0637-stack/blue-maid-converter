const assert = require('node:assert/strict');
const { test } = require('node:test');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const { readSound, loadSoundSettings, saveSoundSettings } = require('../src/sound.cjs');

test('音效导入边界、独立保存、恢复默认与无效设置保护', async () => {
  const directory = await fs.mkdtemp(path.join(os.tmpdir(), 'pet-sound-test-'));
  try {
    assert.deepEqual(await loadSoundSettings(directory), { selected: 'duck', custom: null });
    const source = path.join(directory, '我的音效.MP3');
    // 本测试检查文件读写与设置保存；实际音频解码由界面验证覆盖。
    const bytes = Buffer.from('ID3 test fixture generated by this test');
    await fs.writeFile(source, bytes);
    const custom = await readSound(source);
    assert.equal(custom.name, '我的音效.MP3');
    assert.equal(custom.src, 'data:audio/mpeg;base64,' + bytes.toString('base64'));
    const selected = await saveSoundSettings(directory, { selected: 'custom', custom });
    assert.deepEqual(await loadSoundSettings(directory), selected);
    assert.deepEqual(await fs.readFile(source), bytes, '原音频不能被改动');
    await fs.unlink(source);
    assert.deepEqual(await loadSoundSettings(directory), selected, '删除原音频后应用副本仍可用');
    await assert.rejects(saveSoundSettings(directory, { selected: 'custom', custom: { name: 'bad', src: 'file:///etc/passwd' } }), /无效/);
    assert.deepEqual(await loadSoundSettings(directory), selected, '无效设置不能替换原设置');
    await saveSoundSettings(directory, { selected: 'duck', custom });
    assert.equal((await loadSoundSettings(directory)).custom.src, custom.src, '恢复小黄鸭时保留已导入选项');
    const empty = path.join(directory, 'empty.wav');
    await fs.writeFile(empty, '');
    await assert.rejects(readSound(empty), /非空/);
    await assert.rejects(readSound(directory + '.mp4'), /只支持/);
    await assert.rejects(readSound(directory), /只支持/);
    const large = path.join(directory, 'large.wav');
    const handle = await fs.open(large, 'w');
    await handle.truncate(10 * 1024 * 1024 + 1);
    await handle.close();
    await assert.rejects(readSound(large), /10 MB/);
    await assert.rejects(readSound(source), /无法读取/);
    const blocked = path.join(directory, 'blocked');
    await fs.writeFile(blocked, 'NOT A DIRECTORY');
    await assert.rejects(saveSoundSettings(blocked, { selected: 'duck', custom: null }), /保存失败/);
    await fs.writeFile(path.join(directory, 'click-sound.json'), 'bad JSON');
    await assert.rejects(loadSoundSettings(directory), /无法读取/);
    assert.equal((await fs.readdir(directory)).some(name => name.endsWith('.tmp')), false);
  } finally { await fs.rm(directory, { recursive: true, force: true }); }
});
