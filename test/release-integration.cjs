const assert = require('node:assert/strict');
const sharp = require('sharp');
const ExcelJS = require('exceljs');
const { PDFDocument } = require('pdf-lib');
const { fs, path, zipEntries } = require('../src/conversion-utils.cjs');
const { detectLibreOffice, convertFile, convertFiles, wordXml } = require('../src/converter.cjs');
const { detectExtraTools } = require('../src/formats.cjs');
(async () => {
  const tools = { ...await detectLibreOffice(), ...await detectExtraTools() };
  assert.ok(tools.available && tools.pandoc && tools.qpdf, '发布检查需要 LibreOffice、Pandoc、qpdf');
  const root = path.resolve('artifacts/release-tests'), inputs = path.join(root, 'inputs'), outputs = path.join(root, 'outputs');
  await fs.rm(root, { recursive: true, force: true }); await fs.mkdir(inputs, { recursive: true }); await fs.mkdir(outputs);
  await sharp({ create: { width: 128, height: 96, channels: 4, background: '#67a3da' } }).png().toFile(path.join(inputs, 'image.png'));
  await sharp(path.join(inputs, 'image.png')).jpeg().toFile(path.join(inputs, 'image.jpg'));
  const md = path.join(inputs, 'document.md');
  await fs.writeFile(md, '# 中文标题 RELEASE_CHECK\n\n| 名称 | 值 |\n|---|---|\n| 小鲸 | 123 |\n\n公式 $x^2+1$\n\n![图片](image.png)\n');
  const docx = path.join(inputs, 'document.docx'); await convertFile(md, docx, tools.executable, { target: 'docx', tools });
  const roundTrip = path.join(outputs, 'word.md');
  await convertFile(docx, roundTrip, tools.executable, { target: 'md', tools });
  const text = await fs.readFile(roundTrip, 'utf8'); assert.match(text, /RELEASE_CHECK/); assert.match(text, /中文标题/); assert.ok((await fs.readdir(roundTrip + '.assets')).length);
  const pdf = path.join(inputs, 'pages.pdf'); await convertFile(docx, pdf, tools.executable, { target: 'pdf', tools });
  const document = await PDFDocument.load(await fs.readFile(pdf)); assert.ok(document.getPageCount() >= 1);
  const restored = path.join(outputs, 'restored.docx'); await convertFile(pdf, restored, tools.executable, { target: 'docx', tools }); assert.match(await wordXml(restored), /RELEASE_CHECK/);
  const encrypted = path.join(outputs, 'encrypted.pdf'), decrypted = path.join(outputs, 'decrypted.pdf');
  await convertFile(pdf, encrypted, tools.executable, { target: 'pdf', tools, params: { pdfMode: 'encrypt', password: 'Own release fixture password' } });
  await convertFile(encrypted, decrypted, tools.executable, { target: 'pdf', tools, params: { pdfMode: 'decrypt', password: 'Own release fixture password' } });
  assert.equal((await PDFDocument.load(await fs.readFile(decrypted))).getPageCount(), document.getPageCount());
  const batch = path.join(outputs, 'batch.zip'); await convertFiles([docx, docx], batch, tools.executable, { target: 'md', tools });
  assert.ok([...(await zipEntries(batch)).keys()].some(name => name.endsWith('.png')));
  const csv = path.join(inputs, 'table.csv'); await fs.writeFile(csv, '姓名,值\n小鲸,123\n');
  const xlsx = path.join(outputs, 'table.xlsx'); await convertFile(csv, xlsx, tools.executable, { target: 'xlsx', tools });
  const book = new ExcelJS.Workbook(); await book.xlsx.readFile(xlsx); assert.equal(book.worksheets[0].getCell('A2').value, '小鲸');
  const original = await fs.readFile(md); await assert.rejects(convertFile(md, roundTrip, tools.executable, { target: 'md', tools })); assert.deepEqual(await fs.readFile(md), original);
  console.log('PASS ' + process.platform + ': Word/Markdown 图片公式、Word/PDF 已知文字、PDF 加解密、批量附件、中文 Excel、已有结果与原件保护。');
})().catch(error => { console.error(error.stack); process.exitCode = 1; });
